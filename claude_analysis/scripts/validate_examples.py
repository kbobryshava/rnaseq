#!/usr/bin/env python3
"""Validation of the six required example relationships + negative controls.
Writes reports/validation_examples.md and data/processed/validation_examples.csv
Usage: python validate_examples.py --out <claude_analysis dir>
"""
import argparse, csv, json, os, collections


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--out', required=True); a = ap.parse_args()
    P = os.path.join(a.out, 'data', 'processed')
    ev = [json.loads(l) for l in open(os.path.join(P, 'process_edges_evidence.jsonl'), encoding='utf-8')]
    short = lambda x: x.replace('NFCORE_RNASEQ:', '')
    L = []; rows = []

    def table(title, pred, note, limit=40):
        sel = [e for e in ev if pred(e)]
        L.append(f'\n### {title}\n\n{note}\n')
        if not sel:
            L.append('**No edge found.**'); return
        L.append('| # | source instance (emit) | target instance (input #) | software A -> B | class / tier / confidence | assumptions | channel trail (var @ file:line) | consumer call | producer call |')
        L.append('|---|---|---|---|---|---|---|---|---|')
        seen = set()
        for e in sel:
            k = (e['src_instance'], e['src_emit'], e['dst_instance'], e['dst_input_index'])
            if k in seen: continue
            seen.add(k)
            if len(seen) > limit: break
            trail = ' → '.join(f"`{t['var']}`@{t['at']}" for t in e['channel_trail'][:6])
            L.append(f"| {len(seen)} | `{short(e['src_instance'])}` ({e['src_emit']}) | `{short(e['dst_instance'])}` (#{e['dst_input_index']}) | {e['src_software']} → {e['dst_software']} | {e['edge_class']} / {e['evidence_tier']} / {e['confidence']} | {e['required_param_assumptions'] or '-'} | {trail} | {e['consumer_call']} | {e['producer_call']} |")
            rows.append({'example': title, **{k2: e[k2] for k2 in ('edge_id', 'src_instance', 'src_emit', 'dst_instance', 'dst_input_index', 'edge_class', 'evidence_tier', 'confidence', 'consumer_call', 'producer_call', 'required_param_assumptions')}})
        L.append(f'\n*{min(len(seen), limit)} unique pairs shown. Declaration types of the first pair:* `{sel[0]["src_output_decl"]}` → `{sel[0]["dst_input_decl"]}`')

    L.append('# Validation of required example relationships\n\nGenerated by `scripts/validate_examples.py` from `data/processed/process_edges_evidence.jsonl`. Every row is an instance-level edge; software names are curated canonical names.\n')
    table('1. STAR -> SAMtools', lambda e: e['src_module'] == 'STAR_ALIGN' and e['dst_module'].startswith('SAMTOOLS'),
          'Expected: STAR_ALIGN.bam -> SAMTOOLS_SORT (aligned BAM is sorted). Other rows are alternatives/gating and must be read with their class.')
    table('2a. Trim Galore -> FastQC (post-trim QC)', lambda e: e['src_module'] == 'TRIMGALORE' and e['dst_module'] == 'FASTQC',
          'Trimmed reads are FastQC-ed in the TrimGalore subworkflow.')
    table('2b. Inputs of FastQC (raw) and Trim Galore', lambda e: e['dst_module'] in ('FASTQC', 'TRIMGALORE') and 'FASTQ_FASTQC_UMITOOLS_TRIMGALORE' in e['dst_instance'],
          'Raw FastQC and Trim Galore consume the same upstream read channel: expect NO edge FastQC -> TrimGalore.')
    table('3. Salmon quantification and downstream', lambda e: e['src_module'] == 'SALMON_QUANT' and e['dst_module'] != 'MULTIQC',
          'SALMON_QUANT.results -> CUSTOM_TX2GENE / TXIMETA_TXIMPORT are data dependencies; lib_format_counts -> aligners is the strandedness *metadata* dependency.')
    table('4. Kraken2 -> Bracken', lambda e: e['dst_module'] == 'BRACKEN_BRACKEN' or (e['src_module'] == 'KRAKEN2_KRAKEN2' and e['dst_module'] != 'MULTIQC'),
          'Bracken consumes the Kraken2 report plus the database (UNTAR).')
    table('6. Alternative implementations: outputs of STAR / Sentieon STAR / Parabricks',
          lambda e: e['src_module'] in ('STAR_ALIGN', 'SENTIEON_STARALIGN', 'PARABRICKS_RNAFQ2BAM') and e['dst_module'] != 'MULTIQC' and e['edge_class'] in ('direct', 'merged-channel'),
          'The three implementations are mutually exclusive alternatives (see `conditions` in `process_instances.csv`).', limit=60)

    L.append('\n### 5. Parallel processes sharing an input (negative controls)\n')
    by_src = collections.defaultdict(set)
    for e in ev:
        if e['edge_class'] in ('direct', 'merged-channel'): by_src[(e['src_instance'], e['src_emit'])].add(e['dst_instance'])
    pairs = {(e['src_instance'], e['dst_instance']) for e in ev}
    shared = {k: v for k, v in by_src.items() if len(v) >= 2}
    n_pairs = n_edge = 0; examples = []
    for k, ds in shared.items():
        ds = sorted(ds)
        for i in range(len(ds)):
            for j in range(i + 1, len(ds)):
                n_pairs += 1
                if (ds[i], ds[j]) in pairs or (ds[j], ds[i]) in pairs:
                    n_edge += 1
                    if len(examples) < 15: examples.append(f'- `{short(k[0])}.{k[1]}` fans out to `{short(ds[i])}` and `{short(ds[j])}`, which are also directly connected (chain A->B->C plus A->C, review)')
    L.append(f'Sources with >=2 consumers: {len(shared)}; sibling consumer pairs: {n_pairs}; of which also directly connected: {n_edge}. No edge is ever created between siblings merely because they share an input.\n')
    L.extend(examples)
    bad = [e for e in ev if e['src_module'] == 'FASTQC' and e['dst_module'] == 'TRIMGALORE']
    L.append(f'\n- Negative control FASTQC -> TRIMGALORE (any instance): **{len(bad)} edges** ' + ('(expected 0: PASS)' if not bad else '(FAIL: inspect)'))
    open(os.path.join(a.out, 'reports', 'validation_examples.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    cols = list(rows[0].keys()) if rows else []
    with open(os.path.join(P, 'validation_examples.csv'), 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=cols); w.writeheader(); w.writerows(rows)
    print('rows', len(rows), 'negative-control FASTQC->TRIMGALORE edges:', len(bad))


if __name__ == '__main__':
    main()
